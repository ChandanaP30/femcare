const TABLES: Record<ReportLang, Record<ReportKey, string>> = { en: EN, hi: HI, kn: KN };

export const REPORT_LANG_OPTIONS: { code: ReportLang; label: string }[] = [
  { code: 'en', label: 'English' },
  { code: 'hi', label: 'हिन्दी' },
  { code: 'kn', label: 'ಕನ್ನಡ' },
];

export function reportLangFromCode(code: string): ReportLang {
  if (code.startsWith('hi')) return 'hi';
  if (code.startsWith('kn')) return 'kn';
  return 'en';
}

// Replaces {name} placeholders. A missing value stays visible on purpose, so gaps are noticed.
export function rt(lang: ReportLang, key: ReportKey, params?: Record<string, string | number>): string {
  let s = TABLES[lang][key] ?? EN[key];
  if (params) for (const [k, v] of Object.entries(params)) s = s.split('{' + k + '}').join(String(v));
  return s;
}
