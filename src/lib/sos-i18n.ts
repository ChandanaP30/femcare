export const SOS_TEXT: Record<Language, Record<SosKey, string>> = { en: EN, hi: HI, kn: KN };

export function sosText(lang: Language, key: SosKey, params?: Record<string, string | number>): string {
  let s = (SOS_TEXT[lang] ?? SOS_TEXT.en)[key] ?? SOS_TEXT.en[key];
  if (params) for (const [k, v] of Object.entries(params)) s = s.replace(`{${k}}`, String(v));
  return s;
}
