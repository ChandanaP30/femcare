export function localizeArticle(article: EducationArticle, lang: Language): EducationArticle {
  if (lang === 'en') return article;
  const tr = (lang === 'hi' ? HI : KN)[article.id];
  if (!tr || tr.content.length !== article.content.length) return article;
  return {
    ...article,
    title: tr.title,
    summary: tr.summary,
    content: tr.content,
    references: article.references.map((ref, i) => ({ url: ref.url, label: tr.references[i] ?? ref.label })),
  };
}